TABLES = {"w1": W1, "w4": W4}


class Workload:
    """Draws message lengths shaped like one of the tables, or a mix."""

    def __init__(self, names, seed, cap=MAX_MESSAGE):
        self.cap = cap
        self.parts = []
        for name in names:
            table = TABLES[name]
            total = sum(float(freq) for _, freq in table)
            cumulative, points, running = [], [], 0.0
            for length, freq in table:
                running += float(freq) / total
                cumulative.append(running)
                points.append(length)
            self.parts.append((cumulative, points))
        self.rng = random.Random(seed)

    def draw(self):
        """Return one length: a table chosen with equal chances, a point of
        it by its frequency, and a length uniform from the point before it,
        exclusive, to the point, inclusive, truncated at `cap`."""
        cumulative, points = self.parts[self.rng.randrange(len(self.parts))]
        u = self.rng.random()
        i = min(bisect.bisect_left(cumulative, u), len(points) - 1)
        low = points[i - 1] if i > 0 else 0
        high = points[i]
        length = high if high <= low + 1 else self.rng.randint(low + 1, high)
        return min(length, self.cap)


def payloads(length, max_payload=1424, page_len=65536):
    """Return the payload of each DATA packet of a message of `length` bytes,
    as the engine cuts it: packets of at most `max_payload` bytes that never
    cross a page of `page_len` bytes, and one empty packet for an empty
    message."""
    if length == 0:
        return [0]
    out, offset = [], 0
    while offset < length:
        room = page_len - offset % page_len
        pay = min(length - offset, room, max_payload)
        out.append(pay)
        offset += pay
    return out


def wire_ns(homa_bytes, bits_per_s):
    """Return the nanoseconds a packet of `homa_bytes` Homa bytes takes on a
    link, its framing included, rounded up as the fabric rounds it."""
    return -(-(homa_bytes + WIRE_OVERHEAD) * 8_000_000_000 // bits_per_s)


def one_way_ns(length, bits_per_s, propagation, unsched=40_000, max_payload=1424,
               page_len=65536, all_or_nothing=True):
    """Return the time a message of `length` bytes takes from sender to
    receiver on an idle fabric of one switch, store and forward.

    The sender's card sends the packets back to back, each reaches the switch
    `propagation` after its last bit left, the switch sends each whole once
    its link is free, and the last reaches the receiver `propagation` after
    its last bit left the switch. Under all or nothing scheduling a message
    longer than `unsched` first sends START_MSG and waits for the receiver's
    GRANT, which the receiver sends at once and whose window covers the
    message as it arrives."""
    start = 0
    if all_or_nothing and length > unsched:
        start = 2 * wire_ns(START_MSG, bits_per_s) + 2 * wire_ns(GRANT, bits_per_s) + 4 * propagation
    sent = start
    switch_free = 0
    finish = 0
    for pay in payloads(length, max_payload, page_len):
        w = wire_ns(DATA_HEADER + pay, bits_per_s)
        sent += w
        arrive = sent + propagation
        begin = max(arrive, switch_free)
        finish = begin + w
        switch_free = finish
    return finish + propagation


def unloaded_rpc_ns(length, response_len, bits_per_s, propagation, **kw):
    """Return the time an RPC takes on an idle fabric: its request one way
    and its response the other, since the server answers at once."""
    return one_way_ns(length, bits_per_s, propagation, **kw) + one_way_ns(
        response_len, bits_per_s, propagation, **kw)


def message_wire_bytes(length, max_payload=1424, page_len=65536):
    """Return the bytes the DATA packets of a message take on the wire."""
    return sum(DATA_HEADER + pay + WIRE_OVERHEAD for pay in payloads(length, max_payload, page_len))


def poisson_rpcs(hosts, load, bits_per_s, duration_ns, workload, seed, response_len=0,
                 start_ns=0, clients=None):
    """Return RPCs whose requests take `load` of each client's link on
    average: Poisson arrivals per client host, lengths from `workload`, a
    server chosen uniformly among the other hosts, and responses of
    `response_len` bytes. Each RPC is [client, server, at_ns, length,
    response_len], in time order."""
    rng = random.Random(seed)
    lengths = [workload.draw() for _ in range(20_000)]
    mean_wire = sum(message_wire_bytes(n) for n in lengths) / len(lengths)
    rate_per_ns = load * bits_per_s / 8 / 1e9 / mean_wire
    out = []
    for client in (clients if clients is not None else range(hosts)):
        t = start_ns + rng.expovariate(rate_per_ns)
        while t < start_ns + duration_ns:
            server = rng.randrange(hosts - 1)
            if server >= client:
                server += 1
            out.append([client, server, int(t), workload.draw(), response_len])
            t += rng.expovariate(rate_per_ns)
    out.sort(key=lambda rpc: rpc[2])
    return out


def homa_grant_priority(rank, active, max_sched_prio=MAX_SCHED_PRIO):
    """Return the level of the grant to the message of `rank` among
    `active`, as homa_grant.c lines 282 to 303 compute it."""
    priority = max_sched_prio - rank
    extra = max_sched_prio + 1 - active
    if extra >= 0:
        priority -= extra
    return max(priority, 0)


def split(levels):
    """Return the highest scheduled level of `levels` levels, the lower half
    scheduled, as the devtool's `levels` gives them to the engine."""
    return levels // 2 - 1 if levels >= 2 else 0


def unscheduled_level(cutoffs, length):
    """Return the level of an unscheduled message of `length` bytes: the
    highest level whose cutoff is at least `length`, 0 where none is."""
    for level in range(7, -1, -1):
        if cutoffs[level] >= length:
            return level
    return 0


def equal_share_cutoffs(lengths, levels, unsched=40_000):
    """Return the cutoffs that give each unscheduled level of `levels` an
    equal share of the unscheduled bytes of `lengths`, shorter messages
    higher, exactly over the lengths given, the rule of SIGCOMM 2018 section
    3.4."""
    top = levels - 1
    lowest = split(levels) + 1 if levels >= 2 else 0
    out = [0] * 8
    out[lowest] = MAX_MESSAGE
    shares = top - lowest + 1
    unscheduled = sorted(n for n in lengths if n <= unsched)
    total = sum(unscheduled)
    running, j = 0, 1
    for n in unscheduled:
        running += n
        while j < shares and running >= total * j / shares:
            out[top - j + 1] = n
            j += 1
    return out


def level_shares(cutoffs, lengths, levels, unsched=40_000):
    """Return the unscheduled bytes of `lengths` each unscheduled level of
    `levels` carries under `cutoffs`, highest level first, as fractions of
    an equal share."""
    top = levels - 1
    lowest = split(levels) + 1 if levels >= 2 else 0
    carried = {level: 0 for level in range(lowest, top + 1)}
    unscheduled = [n for n in lengths if n <= unsched]
    for n in unscheduled:
        level = min(max(unscheduled_level(cutoffs, n), lowest), top)
        carried[level] += n
    total = sum(unscheduled)
    share = total / (top - lowest + 1)
    return [carried[level] / share if share else 0.0 for level in range(top, lowest - 1, -1)]


def percentile(values, p):
    """Return the `p` percentile of `values` by nearest rank."""
    ordered = sorted(values)
    if not ordered:
        return math.nan
    rank = max(math.ceil(p / 100 * len(ordered)), 1)
    return ordered[rank - 1]
