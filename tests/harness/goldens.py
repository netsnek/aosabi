"""Aosabi harness: reading and writing the recorded bytes.

The layout is the one of docs/harness.md section 9, and the rule that governs
it is that a golden is generated by running the reference and never by running Aosabi.
Writing is therefore refused unless the papermill parameter `update_goldens` is
true, so that regenerating is a deliberate act that shows up in review as a
diff of golden files.
"""

from __future__ import annotations

import json
from pathlib import Path

from .paths import paths

# The files of one case directory.
CASE_FILES = (
    "request.json",
    "status",
    "headers.json",
    "body.bin",
    "stream.sse",
    "manifest.json",
)

UNSET_NODE_ENV = "unset"

COMMAND_LINE_CAPTURE = "tests/capture/m8_cli.py"


class GoldenMissing(FileNotFoundError):
    """The golden this case compares against is not in the repository yet."""


class GoldenRefused(PermissionError):
    """A write was attempted while `update_goldens` is false."""


def _safe(part: str, what: str) -> str:
    text = str(part)
    if not text or text.startswith("/") or ".." in Path(text).parts:
        raise ValueError("%s must be a plain relative name, got %r" % (what, part))
    return text


def golden_case_dir(
    fixture: str,
    variant: str = "default",
    node_env: str = UNSET_NODE_ENV,
    case_id: str = None,
    goldens_dir: str = None,
    root=None,
) -> Path:
    """The directory of one case, `<fixture>/<variant>/<node_env>/<case-id>/`."""
    base = paths(root, goldens_dir).goldens
    parts = [
        _safe(fixture, "fixture"),
        _safe(variant, "variant"),
        _safe(node_env or UNSET_NODE_ENV, "node_env"),
    ]
    if case_id is not None:
        parts.append(_safe(case_id, "case_id"))
    for part in parts:
        base = base / part
    return base


def golden_path(
    name: str,
    fixture: str = None,
    variant: str = "default",
    node_env: str = UNSET_NODE_ENV,
    case_id: str = None,
    goldens_dir: str = None,
    root=None,
) -> Path:
    """Where one golden file lives.

    With a `fixture` the path is the case layout above. Without one the name is
    read straight under the goldens directory, which is how the families that
    have no case id are reached, `static/`, `sql/`, `mail/` and `http/`.
    """
    name = _safe(name, "name")
    if fixture is None:
        return paths(root, goldens_dir).goldens / name
    return golden_case_dir(fixture, variant, node_env, case_id, goldens_dir, root) / name


def golden_read(
    name: str,
    fixture: str = None,
    variant: str = "default",
    node_env: str = UNSET_NODE_ENV,
    case_id: str = None,
    goldens_dir: str = None,
    root=None,
) -> bytes:
    """Read one golden as bytes, with no decoding and no normalization."""
    path = golden_path(name, fixture, variant, node_env, case_id, goldens_dir, root)
    try:
        return path.read_bytes()
    except FileNotFoundError:
        raise GoldenMissing(
            "no golden at %s, record it from the TypeScript side with update_goldens"
            % paths(root, goldens_dir).rel(path)
        ) from None


def golden_write(
    name: str,
    data: bytes,
    fixture: str = None,
    variant: str = "default",
    node_env: str = UNSET_NODE_ENV,
    case_id: str = None,
    goldens_dir: str = None,
    root=None,
    update_goldens: bool = False,
) -> Path:
    """Write one golden, only under `update_goldens`.

    The caller passes the papermill parameter through, so the refusal names the
    parameter a reader has to set rather than a flag of this function.
    """
    if not update_goldens:
        raise GoldenRefused(
            "refusing to write %s, goldens are recorded only with update_goldens true"
            % name
        )
    if isinstance(data, str):
        raise TypeError("a golden is bytes, encode the text before writing it")
    path = golden_path(name, fixture, variant, node_env, case_id, goldens_dir, root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(bytes(data))
    return path


def recorded_by_the_command_line(path) -> bool:
    """A walk over the answers the goldens of the other milestones record leaves
    them out, so its corpus and its counts stay what those milestones measured.
    The manifest names the producer as an object whose script is
    `COMMAND_LINE_CAPTURE`.
    """
    directory = Path(path)
    if not directory.is_dir():
        directory = directory.parent
    manifest = directory / "manifest.json"
    if not manifest.is_file():
        return False
    try:
        producer = json.loads(manifest.read_text(encoding="utf-8")).get("produced_by")
    except (ValueError, AttributeError):
        return False
    return isinstance(producer, dict) and producer.get("script") == COMMAND_LINE_CAPTURE
